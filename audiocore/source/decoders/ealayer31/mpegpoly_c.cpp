void CMpegBase::PolySynth(int channel, float* pSamples, float* pBand)
{
    float* b0;
    float (*buf)[0x120];
    int bo1;
    int bob1;
    int bob2;

    mBandOffset[channel]--;
    mBandOffset[channel] &= 0xf;
    bob1 = mBandOffset[channel] & 1;
    bob2 = bob1 ^ 1;
    bo1 = mBandOffset[channel] + bob2;
    buf = reinterpret_cast<float (*)[0x120]>(mpLoadedPolySynthHistoryF[channel][0]);
    b0 = buf[bob2];
    dct64(buf[bob1] + ((mBandOffset[channel] + bob1) & 0xf), b0 + bo1, pBand);
    int count = 16;
    const float* window = decwin + 16 - bo1;
    int j;

    for (j = count; j; j--, b0 += 16, window += 32, pSamples++)
    {
        float sum;
        sum = window[0] * b0[0];
        sum -= window[1] * b0[1];
        sum += window[2] * b0[2];
        sum -= window[3] * b0[3];
        sum += window[4] * b0[4];
        sum -= window[5] * b0[5];
        sum += window[6] * b0[6];
        sum -= window[7] * b0[7];
        sum += window[8] * b0[8];
        sum -= window[9] * b0[9];
        sum += window[10] * b0[10];
        sum -= window[11] * b0[11];
        sum += window[12] * b0[12];
        sum -= window[13] * b0[13];
        sum += window[14] * b0[14];
        sum -= window[15] * b0[15];
        *pSamples = sum;
    }

    {
        float sum;
        sum = window[0] * b0[0];
        sum += window[2] * b0[2];
        sum += window[4] * b0[4];
        sum += window[6] * b0[6];
        sum += window[8] * b0[8];
        sum += window[10] * b0[10];
        sum += window[12] * b0[12];
        sum += window[14] * b0[14];
        *pSamples = sum;
        b0 -= 16;
        window -= 32;
        pSamples++;
    }

    window += bo1 << 1;

    for (j = (count - 1); j; j--, b0 -= 16, window -= 32, pSamples++)
    {
        float sum;
        sum = -window[-1] * b0[0];
        sum -= window[-2] * b0[1];
        sum -= window[-3] * b0[2];
        sum -= window[-4] * b0[3];
        sum -= window[-5] * b0[4];
        sum -= window[-6] * b0[5];
        sum -= window[-7] * b0[6];
        sum -= window[-8] * b0[7];
        sum -= window[-9] * b0[8];
        sum -= window[-10] * b0[9];
        sum -= window[-11] * b0[10];
        sum -= window[-12] * b0[11];
        sum -= window[-13] * b0[12];
        sum -= window[-14] * b0[13];
        sum -= window[-15] * b0[14];
        sum -= window[-0] * b0[15];
        *pSamples = sum;
    }
}

